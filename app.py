def sync(t):
 if t['status']!='active':return t
 now=current()
 if t['hidden_since'] is not None and t['mode']=='exam' and now-t['hidden_since']>GRACE:
  run("UPDATE attempts SET status='disqualified',ended_at=:at WHERE id=:id AND status='active'",{'at':now,'id':t['id']},True);log(t['id'],'disqualified','Outside page over grace period')
 elif now-t['started_at']>=t['duration']*60:
  run("UPDATE attempts SET status='expired',ended_at=:at WHERE id=:id AND status='active'",{'at':now,'id':t['id']},True);log(t['id'],'time_expired')
 return attempt_for_user(t['id'])

