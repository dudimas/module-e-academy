def check_csrf():
 supplied=request.headers.get('X-CSRF-Token') or request.form.get('csrf')
 if not supplied or not hmac.compare_digest(supplied,session.get('csrf','')):abort(403)
def token():return '<input type="hidden" name="csrf" value="'+escape(csrf())+'">'
